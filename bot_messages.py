def format_bot_message(msg_id: str, **values) -> str:
    """取文案并替换 {key} 占位符；未提供的占位符替换为空串。"""
    message = MESSAGES.get(msg_id)
    if message is None:
        raise KeyError(f"Unknown bot message id: {msg_id}")
    for key, value in values.items():
        message = message.replace("{" + key + "}", str(value if value is not None else ""))
    return message
